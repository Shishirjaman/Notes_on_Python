# boolean is a logical operator in python (True, False)
a = True
print(a)

b = False
print(b)

# boolean operator mainly used for checking condition or used as a flag in the code
print(a == b) # here, == is equal operator

# in boolean
# True and True = True
# True and False = False
# False and True = False
# False and False = False
# True or True = True
# True or False = True
# False or True = True
# False or False = False

# Conditional operator
# == equal to operator
# != not equal to operator
# > less than operator
# < greater than operator
# >= less than equal to operator
# <= greater than equal to operator

a = 3
b = 5
print(a == b)
print(a > b)
print(a < b)
print(a >= b)
print( a <= b)

a = 10
b = 10
print(a >= b)
print(a <= b) 