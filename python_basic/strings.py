# in python anything that we write inside of the ''(single quote) and ""(double quote)
# is considered as string
print("Hello World")
print ('Bonjour tout le monde')

# can concatenate two strings by using (+) operator
print('Hi!'+"it's me") # to mention: here it's has a single inverted comma, so I put the words inside double quote

# without writing same string multiple times we can use (*) operator to assign or print same string multiple times
print("Hello world! \n" * 5)

# we can do same concatenate and multiplication operation by assigning string to a variable as well
string1 = "Bonjour!"
string2 = "tout le monde"
print(string1)
print(string2)
print(string1 + string2)
print(string1 * 2 + string2)