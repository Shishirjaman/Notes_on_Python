a = 5
print (type(a))

# str() method used to explicitly declare or make a variable string
b = str(a)
print(b)
print(type(b))

# float() method used to explicitly declare or make a variable string
c = float(a)
print(c)
print(type(c))

# int() method used to explicitly declare or make a variable string
a = int(c)
print(a)
print(type(a))

