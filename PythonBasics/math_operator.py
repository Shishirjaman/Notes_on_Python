# Addition (+): add among the numbers 
print(5 + 10) # will add 5 + 10 and output 15

# Subtraction (-): reduce the value of one number from another
print(10 - 5) # will subtract 5 from 10 and output 5

# Multiplication (*): multiply the numbers 
print(3 * 4) # multiplys 3 with 4 and outputs 12

# Exponential (**): perform exponential operation (power) to the numbers
print(3**4) # multiplys 3 with 3 4times (3*3*3*3) and outputs 81

# Division (/): perform division(float) operation to the number
# in python single / returns or outputs float number
print(20 / 5) # devide 20 by 5 and ouputs 4.0

# Division (//): perform division(integer) operation to the number
# in python double // returns or outputs integer number
print (25 // 7) # devide 25 by y and outputs 3

# Modulo (%): perform modulas operation to the number means it returns
# remaining value after fully diving a number by another number
print(22 % 8) # ouputs 6 (8*2=16< 22 < 8*3=24, so 22 - 16 = 6)